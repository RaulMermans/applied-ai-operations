import type { JsonObject, JsonValue } from "@aao/contracts";
import type { ToolboxDescription, ToolboxToolDescription } from "./catalog.js";

// Generated catalog documents. Both renderings derive only from
// `describeToolbox` (the manifest plus the actual Tool definitions), so
// docs never duplicate a Tool id, version, permission, or description by
// hand. Package-internal: not exported from the root; the generator script
// and the drift test import it directly.

/** Canonical JSON rendering (2-space indent, trailing newline): byte-stable for the drift check. */
export function renderToolboxCatalogJson(description: ToolboxDescription): string {
  return `${JSON.stringify(description, null, 2)}\n`;
}

const CONSTRAINTS = ["minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems", "uniqueItems", "maxProperties"] as const;

function typeOf(schema: JsonObject): string {
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(" \\| ");
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map((option) => typeOf(option as JsonObject)).join(" \\| ");
  if (schema.type === "array" && schema.items !== undefined) return `${typeOf(schema.items as JsonObject)}[]`;
  return typeof schema.type === "string" ? schema.type : "any";
}

function limitsOf(schema: JsonObject): string {
  const own = CONSTRAINTS.filter((key) => schema[key] !== undefined).map((key) => (key === "uniqueItems" ? "unique" : `${key} ${String(schema[key])}`));
  const items = schema.items as JsonObject | undefined;
  const nested = items ? CONSTRAINTS.filter((key) => items[key] !== undefined).map((key) => `items.${key} ${String(items[key])}`) : [];
  return [...own, ...nested].join(", ") || "—";
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

function inputTable(schema: JsonObject): string[] {
  const properties = (schema.properties ?? {}) as Record<string, JsonObject>;
  const required = new Set((schema.required ?? []) as string[]);
  return [
    "| Field | Type | Required | Limits | Notes |",
    "| --- | --- | --- | --- | --- |",
    ...Object.entries(properties).map(([name, property]) => `| \`${name}\` | ${typeOf(property)} | ${required.has(name) ? "yes" : "no"} | ${limitsOf(property)} | ${cell(typeof property.description === "string" ? property.description : "")} |`),
  ];
}

function outputSummary(schema: JsonObject): string[] {
  const properties = (schema.properties ?? {}) as Record<string, JsonObject>;
  return Object.entries(properties).map(([name, property]) => {
    const fields = property.properties ? Object.keys(property.properties as JsonObject).map((field) => `\`${field}\``).join(", ") : typeOf(property);
    return `- \`${name}\`: ${fields}`;
  });
}

function toolSection(tool: ToolboxToolDescription): string[] {
  return [
    `## \`${tool.toolRef.id}\``,
    "",
    `**${tool.name}**`,
    "",
    "| Tool | Version | Category | Permission | Retry safety | Status |",
    "| --- | --- | --- | --- | --- | --- |",
    `| \`${tool.toolRef.id}\` | ${tool.toolRef.version} | ${tool.category} | ${tool.permissionClasses.map((permission) => `\`${permission}\``).join(", ")} | ${tool.retrySafety} | ${tool.status}${tool.replacementRef ? ` (replaced by \`${tool.replacementRef.id}@${tool.replacementRef.version}\`)` : ""} |`,
    "",
    tool.description,
    "",
    `Tags: ${tool.tags.map((tag) => `\`${tag}\``).join(", ")}`,
    "",
    "**When to use**",
    "",
    ...tool.whenToUse.map((line) => `- ${line}`),
    "",
    "**When not to use**",
    "",
    ...tool.whenNotToUse.map((line) => `- ${line}`),
    "",
    "**Input and limits**",
    "",
    ...inputTable(tool.inputSchema),
    "",
    "**Output**",
    "",
    ...outputSummary(tool.outputSchema),
    "",
    "**Examples**",
    "",
    ...tool.examples.flatMap((example) => [`- ${example.title}${example.notes ? ` — ${example.notes}` : ""}`, "", "  ```json", `  ${JSON.stringify(example.input as JsonValue)}`, "  ```", ""]),
  ];
}

/** Human-readable catalog. Permission and retry safety come from the Tool definitions, never from Toolbox metadata. */
export function renderToolboxCatalogMarkdown(description: ToolboxDescription): string {
  const { toolbox } = description;
  const lines = [
    `# ${toolbox.name} (\`${toolbox.id}@${toolbox.version}\`)`,
    "",
    "<!-- Generated by `pnpm --filter @aao/toolbox catalog:generate` from describeToolbox(coreToolbox). Do not edit by hand: the drift test fails on any difference. -->",
    "",
    toolbox.description,
    "",
    `Catalog fingerprint: \`${toolbox.fingerprint}\` (catalog identity, not a code attestation). Authority: **none** — this catalog describes Tools; the Tool Registry, the Tool Runtime support gate, and Authorization decide every execution. Discovery grants no permission.`,
    "",
    "| Tool | Version | Category | Permission | Status | Name |",
    "| --- | --- | --- | --- | --- | --- |",
    ...description.tools.map((tool) => `| [\`${tool.toolRef.id}\`](#${tool.toolRef.id.replace(/[^a-z0-9_-]/g, "")}) | ${tool.toolRef.version} | ${tool.category} | ${tool.permissionClasses.map((permission) => `\`${permission}\``).join(", ")} | ${tool.status} | ${cell(tool.name)} |`),
    "",
    ...description.tools.flatMap(toolSection),
  ];
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
